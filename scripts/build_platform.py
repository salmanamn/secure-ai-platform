"""Build the tenants' platform objects from platform/tenants.yaml (D15).

uv run python scripts/build_platform.py            write platform/generated/<tenant>.yaml
uv run python scripts/build_platform.py --check    exit 1 if a generated file is not what the spec gives

Per tenant, in apply order: the Namespace (owner labels, Pod Security "restricted", D7), a ResourceQuota (the
spec's numbers, no LoadBalancer or NodePort Services, D17), a LimitRange (per-container maximum, no defaults, D17),
RoleBindings of the platform's tenant roles to the tenant's groups (D16), and the baseline network policies: deny
everything in and out, then allow DNS to kube-system only (D18). Every object carries platform.lab/managed=true.
The cluster roles themselves are hand-written in platform/cluster/roles.yaml.

The unit tests run every Gatekeeper rule over these objects: the platform's own objects obey the platform's policy.
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "platform" / "tenants.yaml"
OUT = ROOT / "platform" / "generated"
MANAGED = {"platform.lab/managed": "true"}
HEADER = "# Generated by scripts/build_platform.py from platform/tenants.yaml: don't edit by hand.\n"
ROLES = {"admins": "platform-tenant-admin", "readers": "platform-tenant-reader"}


def load_spec(path: Path = SPEC) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def namespace(tenant: dict) -> dict:
    labels = {
        "platform.lab/tenant": tenant["name"],
        "platform.lab/owner": tenant["owner"],
        "platform.lab/source": tenant["source"],
        **MANAGED,
    }
    labels |= {f"pod-security.kubernetes.io/{mode}": "restricted" for mode in ("enforce", "warn", "audit")}
    return {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": tenant["name"], "labels": labels}}


def meta(tenant: dict, name: str) -> dict:
    return {"name": name, "namespace": tenant["name"], "labels": dict(MANAGED)}


def quota(tenant: dict) -> dict:
    hard = {key: str(value) for key, value in tenant["quota"].items()}
    hard |= {"services.loadbalancers": "0", "services.nodeports": "0"}
    return {
        "apiVersion": "v1",
        "kind": "ResourceQuota",
        "metadata": meta(tenant, "platform-quota"),
        "spec": {"hard": hard},
    }


def limit_range(tenant: dict, limits: dict) -> dict:
    maximum = {key: str(value) for key, value in limits.items()}
    return {
        "apiVersion": "v1",
        "kind": "LimitRange",
        "metadata": meta(tenant, "platform-limits"),
        "spec": {"limits": [{"type": "Container", "max": maximum}]},
    }


def role_binding(tenant: dict, group: str, role: str) -> dict:
    return {
        "apiVersion": "rbac.authorization.k8s.io/v1",
        "kind": "RoleBinding",
        "metadata": meta(tenant, f"tenant-{group}"),
        "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "ClusterRole", "name": role},
        "subjects": [
            {"apiGroup": "rbac.authorization.k8s.io", "kind": "Group", "name": f"tenant:{tenant['name']}:{group}"}
        ],
    }


def default_deny(tenant: dict) -> dict:
    return {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "NetworkPolicy",
        "metadata": meta(tenant, "platform-default-deny"),
        "spec": {"podSelector": {}, "policyTypes": ["Ingress", "Egress"]},
    }


def allow_dns(tenant: dict) -> dict:
    peer = {
        "namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": "kube-system"}},
        "podSelector": {"matchLabels": {"k8s-app": "kube-dns"}},
    }
    ports = [{"protocol": "UDP", "port": 53}, {"protocol": "TCP", "port": 53}]
    return {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "NetworkPolicy",
        "metadata": meta(tenant, "platform-allow-dns"),
        "spec": {"podSelector": {}, "policyTypes": ["Egress"], "egress": [{"to": [peer], "ports": ports}]},
    }


def tenant_objects(tenant: dict, limits: dict) -> list[dict]:
    return [
        namespace(tenant),
        quota(tenant),
        limit_range(tenant, limits),
        *(role_binding(tenant, group, role) for group, role in ROLES.items()),
        default_deny(tenant),
        allow_dns(tenant),
    ]


def outputs(spec: dict | None = None) -> dict[Path, str]:
    spec = load_spec() if spec is None else spec
    files = {}
    for tenant in spec["tenants"]:
        documents = tenant_objects(tenant, spec["limits"])
        body = yaml.safe_dump_all(documents, sort_keys=False, explicit_start=True)
        files[OUT / f"{tenant['name']}.yaml"] = HEADER + body
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare with the generated files, write nothing")
    args = parser.parse_args()
    files = outputs()
    stale = [p for p, text in files.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    extra = sorted(set(OUT.glob("*.yaml")) - set(files)) if OUT.is_dir() else []
    if args.check:
        for path in stale:
            print(f"FAIL {path.relative_to(ROOT)} is stale: run uv run python scripts/build_platform.py")
        for path in extra:
            print(f"FAIL {path.relative_to(ROOT)} has no tenant in platform/tenants.yaml: delete it")
        if stale or extra:
            return 1
        print(f"OK   {len(files)} tenants up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path in extra:
        path.unlink()
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} tenants to platform/generated/: {', '.join(p.stem for p in files)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
