"""Render each tenant release (D25): the tenant's own chart at a pinned commit, with the platform's values.

uv run python scripts/render_tenants.py            write platform/rendered/<tenant>.yaml
uv run python scripts/render_tenants.py --check    exit 1 if a rendered file is not what the release gives

A release is platform/releases/<tenant>.yaml: the chart's repository, commit and path, and the values. The chart is
fetched at exactly that commit into .cache/tenants/ (git, by commit id), rendered with `helm template <tenant> -n
<tenant>` at the Helm version in versions.env, and written with a header naming what it came from. Rendered files
are committed: the unit tests run every Gatekeeper rule over them, and `platform.sh tenant <name>` applies them.
"""

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
RELEASES = ROOT / "platform" / "releases"
OUT = ROOT / "platform" / "rendered"
CACHE = ROOT / ".cache" / "tenants"
COMMIT = re.compile(r"^[0-9a-f]{40}$")
DIGEST = re.compile(r"^sha256:[0-9a-f]{64}$")


def versions() -> dict[str, str]:
    lines = (ROOT / "versions.env").read_text(encoding="utf-8").splitlines()
    return dict(line.split("=", 1) for line in lines if "=" in line and not line.startswith("#"))


def load_releases() -> dict[str, dict]:
    return {p.stem: yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted(RELEASES.glob("*.yaml"))}


def problems(name: str, release: dict) -> list[str]:
    found = []
    if release.get("tenant") != name:
        found.append(f"{name}: tenant is {release.get('tenant')!r}, the file is {name}.yaml")
    if not COMMIT.match(str(release["chart"]["ref"])):
        found.append(f"{name}: chart.ref must be a full commit id (40 hex), not a branch or tag")
    if not DIGEST.match(str(release["values"]["image"]["digest"])):
        found.append(f"{name}: values.image.digest must be sha256:<64 hex>")
    return found


def run(*args: str, cwd: Path | None = None) -> str:
    result = subprocess.run(args, cwd=cwd, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise SystemExit(f"FAIL {' '.join(args[:3])}: {(result.stderr or result.stdout).strip()[-300:]}")
    return result.stdout


def chart_at(release: dict) -> Path:
    """The chart directory at the pinned commit (fetched once; the cache is keyed by the commit)."""
    ref = release["chart"]["ref"]
    work = CACHE / f"{release['tenant']}-{ref[:12]}"
    if not (work / ".git").is_dir() or run("git", "rev-parse", "HEAD", cwd=work).strip() != ref:
        work.mkdir(parents=True, exist_ok=True)
        run("git", "init", "-q", cwd=work)
        run("git", "fetch", "-q", "--depth", "1", release["chart"]["repo"], ref, cwd=work)
        run("git", "checkout", "-q", "--detach", "FETCH_HEAD", cwd=work)
    return work / release["chart"]["path"]


def helm_version() -> str:
    return run("helm", "version", "--short").strip().split("+")[0]


def render(release: dict) -> str:
    wanted = versions()["HELM_VERSION"]
    if (have := helm_version()) != wanted:
        raise SystemExit(f"FAIL helm {have}: renders are made with helm {wanted} (versions.env), or they drift")
    tenant = release["tenant"]
    with tempfile.NamedTemporaryFile("w", suffix=".yaml", encoding="utf-8") as values:
        yaml.safe_dump(release["values"], values, sort_keys=False)
        values.flush()
        body = run("helm", "template", tenant, str(chart_at(release)), "--namespace", tenant, "-f", values.name)
    header = (
        "# Generated by scripts/render_tenants.py from platform/releases/{t}.yaml: don't edit by hand.\n"
        "# chart: {repo} {path} at {ref}\n"
        "# image: {image}@{digest}\n"
        "# helm: {helm}\n"
    ).format(
        t=tenant,
        repo=release["chart"]["repo"],
        path=release["chart"]["path"],
        ref=release["chart"]["ref"],
        image=release["values"]["image"]["repository"],
        digest=release["values"]["image"]["digest"],
        helm=wanted,
    )
    return header + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare with the rendered files, write nothing")
    args = parser.parse_args()
    releases = load_releases()
    errors = [p for name, release in releases.items() for p in problems(name, release)]
    for error in errors:
        print(f"FAIL {error}")
    if errors:
        return 1
    files = {OUT / f"{name}.yaml": render(release) for name, release in releases.items()}
    stale = [p for p, text in files.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    extra = sorted(set(OUT.glob("*.yaml")) - set(files)) if OUT.is_dir() else []
    if args.check:
        for path in stale:
            print(f"FAIL {path.relative_to(ROOT)} is stale: run uv run python scripts/render_tenants.py")
        for path in extra:
            print(f"FAIL {path.relative_to(ROOT)} has no release in platform/releases: delete it")
        if stale or extra:
            return 1
        print(f"OK   {len(files)} tenant release(s) rendered as committed")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path in extra:
        path.unlink()
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        kinds = len(re.findall(r"^kind: ", text, re.M))
        print(f"wrote {path.relative_to(ROOT)}: {kinds} objects")
    return 0


if __name__ == "__main__":
    sys.exit(main())
